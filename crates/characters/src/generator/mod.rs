//! The generator (CK-369, characters slice 7): characters made from the recipe, with a generated past, a role, languages, and the real
//! families, slots, households and marriage candidates the 768 start and the marriage pool need.
//!
//! **One transaction.** `generate`, a slot fill, `complete_household` and a marriage candidate each make all their records, heads, moves,
//! assignments and links together or not at all. The work runs on the store itself behind a journal (`Txn`): the records it makes are
//! removed, the existing records it touched are put back, the identifier counter is reset and the head moves are undone when anything
//! refuses, and the archive records and life-log lines it makes are held back (`Stage`, `StagedLog`) until everything has been decided.
//! The commit publishes the archive records as one step (`ArchiveSink::append_all`: all or none) and then the lines, which are output: a
//! line that cannot be appended does not undo the commit.
//!
//! No floating point. Every draw is on a stream named by its purpose: the dates on a stream of the request's identity (its pop, the
//! caller's request key and the day), the rest on the stream of the character they are for.
