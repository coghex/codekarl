//! The main loop: setup from the first request batch, passes of bounded work, and teardown.
//!
//! The loop owns the backend and the presenter in [`ManuallyDrop`]: no `Drop` releases them, so a panic
//! unwinding through [`run`], or a teardown that could not prove the resources released, leaves them
//! alone. Only the explicit teardown destroys anything.

use std::fmt::Arguments;
use std::mem::ManuallyDrop;
use std::sync::Arc;
use std::sync::atomic::{AtomicBool, Ordering};
use std::time::{Duration, Instant};

use ck_input::Mapper;
use ck_log::Level;

