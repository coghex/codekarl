use crate::requests::RequestReader;
use crate::settings::{LoopSettings, UpdateControl, UpdateSettings};

/// A monotonic clock used by the loop and deterministic scheduler tests.
pub trait Clock {
    /// The current monotonic instant.
    fn now(&self) -> Instant;
}

struct SystemClock;

impl Clock for SystemClock {
    fn now(&self) -> Instant {
        Instant::now()
    }
}

/// How a [`run`] ended. Every end other than [`Unproven`](Self::Unproven) means teardown completed.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum LoopEnd {
    /// The UI never asked for a window; the run continues as a run without one.
    NoWindow,
    /// The window was closed: an accepted close request, or a `close` from the request slot.
    Closed,
    /// The quit flag was seen.
    Quit,
    /// The UI's callback failed; the message carries its name and traceback.
    CallbackFailed {
        /// The failure.
        message: String,
    },
    /// Window creation, the presenter's start, or the UI link failed.
    Failed {
        /// The failure.
        message: String,
    },
    /// The presenter reported `Failed` (`the presenter failed: ...`): during the passes, or **after** the
    /// loop had otherwise ended, when teardown took the reports of a presenter it had observed finished.
    /// A presenter may report a failure and still prove its resources released, so this end is a failed
    /// run with a completed teardown. When another failure already ended the loop, that one stays the end
    /// and each presenter failure found later gets one `error` record instead; see [`run`].
    PresenterFailed {
        /// The failure.
        message: String,
    },
    /// Teardown could not prove the resources released: nothing was destroyed and nothing will be
    /// dropped. The executable ends the process (issue 6).
    Unproven {
        /// Why.
        reason: String,
    },
}

/// How long a record may wait to be admitted to the logger.
const LOG_WAIT: Duration = Duration::from_millis(100);
/// The slice of the presenter-end polls during teardown.
const POLL_SLICE: Duration = Duration::from_millis(2);

/// The most reports teardown takes from a presenter that was observed finished (or whose deadline was
/// missed). A finished presenter's queue is finite, so this is a bound against a malformed presenter that
/// never stops reporting, not a limit on a well-behaved one: it is far above anything a presenter queues,
/// and exceeding it is a reported failure.
const TERMINAL_REPORTS: usize = 4096;

/// The text of a presenter failure, as the run's failure and as a record.
fn presenter_failure(message: &str) -> String {
    format!("the presenter failed: {message}")
}

/// Emits one record in category `window` through `log_within`: the loop never uses the waiting `log`.
fn log(level: Level, message: Arguments<'_>) {
    let at = Instant::now()
        .checked_add(LOG_WAIT)
        .unwrap_or_else(Instant::now);
    let _ = ck_log::log_within!(level, at, "window", "{message}");
}

/// What exists and so has to be torn down.
#[derive(Default)]
struct Parts {
    /// `create_window` succeeded and `destroy_window` has not run.
    window: bool,
    /// The notifier was armed by this loop.
    armed: bool,
    /// `Presenter::start` returned `Ok`: a render thread exists.
    presenter_started: bool,
    /// `window opened` was logged, so `window closed` is too.
    opened: Option<()>,
}

/// Where the `Opened` event is.
#[derive(Clone, Copy, PartialEq, Eq)]
enum OpenedEvent {
    /// The presenter has not reported its first frame.
    Waiting,
    /// Decided, and not yet offered to the UI link.
    ToPost,
    /// Refused by the UI link with `Full`; offered again on a later pass.
    Blocked,
    /// Posted: it is sent once.
    Posted,
}

/// Where the close request is. At most one is ever outstanding.
#[derive(Clone, Copy, PartialEq, Eq)]
enum CloseEvent {
    /// None outstanding.
    Idle,
    /// Generated by a press and not yet offered to the UI link.
    ToPost(CloseSource),
    /// Refused by the UI link with `Full`; offered again on a later pass.
    Blocked(CloseSource),
    /// Posted, and not yet answered.
    Outstanding,
}

/// The state that carries from one pass to the next.
struct Pass {
    /// The previous pass observed the presenter reports and the UI answers exhausted, not just capped.
    exhausted: bool,
    opened: OpenedEvent,
    close: CloseEvent,
    /// The latest pixel size reported by the backend, if it changed since it was passed on.
    new_size: Option<PixelSize>,
    redraw: bool,
}

/// The loop's input state: the mapper that turns normalised key events into actions, and the window's focus.
struct InputState {
    mapper: Mapper,
    /// Whether the window has key focus (the native layer reports each change). M5-7's pause rule reads it.
    focused: bool,
    minimized: bool,
    pixel_size: PixelSize,
}

#[derive(Clone, Copy)]
struct OutstandingUpdate {
    sequence: u64,
    epoch: u64,
}

struct UpdateScheduler {
    settings: UpdateSettings,
    control: UpdateControl,
    metrics: Option<LoopMetrics>,
    active: bool,
    epoch: u64,
    origin: Option<Instant>,
    next_index: u128,
    pending: Option<Instant>,
    outstanding: Option<OutstandingUpdate>,
    suppressed_epoch: Option<u64>,
    sequence: u64,
    last_post: Option<Instant>,
}

impl UpdateScheduler {
    fn new(settings: UpdateSettings) -> Self {
        Self {
            control: settings.control(),
            metrics: settings.metrics().cloned(),
            settings,
            active: false,
            epoch: 0,
            origin: None,
            next_index: 0,
            pending: None,
            outstanding: None,
            suppressed_epoch: None,
            sequence: 0,
            last_post: None,
        }
    }

    fn deadline(&self) -> Option<Instant> {
        let origin = self.origin?;
        origin.checked_add(multiply_duration(self.settings.period(), self.next_index)?)
    }

    fn refresh(&mut self, now: Instant, eligible: bool, epoch: u64) {
        let enabled = eligible && self.suppressed_epoch != Some(epoch);
        let new_epoch = epoch != self.epoch;
        self.epoch = epoch;
        let should_activate = enabled;
        if !should_activate {
            if self.active {
                self.pending = None;
            }
            self.active = false;
            self.origin = None;
            self.next_index = 0;
            return;
        }
        if !self.active || new_epoch {
            self.active = true;
            self.origin = Some(now);
            // Opportunity zero is the immediate first update we queue below; the next grid point
            // is one complete period later.
            self.next_index = 1;
            self.pending = Some(now);
            self.last_post = None;
            return;
        }
        self.capture_due(now);
    }

    /// The loop is beginning its teardown at `now`: examines the schedule through it (counting the opportunities that fell due since
    /// the last pass and were coalesced, without posting anything) and tells the measurement windows it has accounted through `now`.
    fn finish(&mut self, now: Instant) {
        if self.active {
            self.capture_due(now);
        }
        if let Some(metrics) = &self.metrics {
            metrics.accounted(now);
        }
    }

    fn capture_due(&mut self, now: Instant) {
        let Some(origin) = self.origin else { return };
        let period_nanos = self.settings.period().as_nanos();
        let elapsed = now.saturating_duration_since(origin).as_nanos();
        let latest = elapsed / period_nanos;
        if latest >= self.next_index
            && let Some(at) = origin.checked_add(
                multiply_duration(self.settings.period(), latest).unwrap_or(Duration::MAX),
            )
        {
            if let Some(metrics) = &self.metrics {
                // The opportunities that fell due and are coalesced: those between the last captured one and this one, and the
                // earlier capture still waiting to be posted. Each is counted by the time it fell due.
                if let Some(earlier) = self.pending {
                    metrics.missed(earlier, self.settings.period(), 1);
                }
                let skipped = latest - self.next_index;
                if let Some(first) = origin.checked_add(
                    multiply_duration(self.settings.period(), self.next_index)
                        .unwrap_or(Duration::MAX),
                ) {
                    metrics.missed(first, self.settings.period(), skipped);
                }
            }
            self.pending = Some(at);
            self.next_index = latest.saturating_add(1);
        }
    }

    fn answer(&mut self, event: &UiEvent, answer: &Answer) -> Result<(), LoopEnd> {
        let UiEvent::Update(update) = event else {
            return Ok(());
        };
        let Some(outstanding) = self.outstanding else {
            return Ok(());
        };
        if outstanding.sequence != update.sequence {
            return Ok(());
        }
        self.outstanding = None;
        match answer {
            Answer::Failed { message } => Err(LoopEnd::CallbackFailed {
                message: message.clone(),
            }),
            Answer::NotRegistered => {
                self.suppressed_epoch = Some(outstanding.epoch);
                Ok(())
            }
            Answer::Returned | Answer::Accept | Answer::Decline => Ok(()),
        }
    }
}

fn multiply_duration(duration: Duration, multiplier: u128) -> Option<Duration> {
    let nanos = duration.as_nanos().checked_mul(multiplier)?;
    let seconds = u64::try_from(nanos / 1_000_000_000).ok()?;
    let subsecond = u32::try_from(nanos % 1_000_000_000).ok()?;
    Some(Duration::new(seconds, subsecond))
}

struct Loop<'a, B: Backend, P: Presenter<Handles = B::Handles>, U: UiLink> {
    input: InputState,
    backend: &'a mut B,
    presenter: &'a mut P,
    ui: &'a mut U,
    requests: &'a RequestReader,
    notifier: &'a Notifier,
    quit: &'a AtomicBool,
    settings: &'a LoopSettings,
    clock: &'a dyn Clock,
    points: (u32, u32),
    updates: Option<UpdateScheduler>,
    parts: Parts,
}

/// Runs the window's main loop on the calling (main) thread, and returns how it ended.
///
/// `backend` and `presenter` are held so that only the explicit teardown releases them (see the module
/// documentation). `requests` is the slot's reader, `notifier` the shared notifier and `quit` the shared
/// quit flag. See the crate documentation for the setup, the passes and the teardown.
pub fn run<B, P, U>(
    backend: B,
    presenter: P,
    ui: U,
    requests: &RequestReader,
    notifier: &Arc<Notifier>,
    quit: &AtomicBool,
    settings: &LoopSettings,
) -> LoopEnd
where
    B: Backend,
    P: Presenter<Handles = B::Handles>,
    U: UiLink,
{
    run_with_clock(
        backend,
        presenter,
        ui,
        requests,
        notifier,
        quit,
        settings,
        &SystemClock,
    )
}

/// Runs with an injected monotonic clock. Production callers normally use [`run`].
#[expect(
    clippy::too_many_arguments,
    reason = "mirrors run while adding only its test clock"
)]
pub fn run_with_clock<B, P, U, C>(
    backend: B,
    presenter: P,
    mut ui: U,
    requests: &RequestReader,
    notifier: &Arc<Notifier>,
    quit: &AtomicBool,
    settings: &LoopSettings,
    clock: &C,
) -> LoopEnd
where
    B: Backend,
    P: Presenter<Handles = B::Handles>,
    U: UiLink,
    C: Clock,
{
    let mut backend = ManuallyDrop::new(backend);
    let mut presenter = ManuallyDrop::new(presenter);
    let end = drive(
        &mut *backend,
        &mut *presenter,
        &mut ui,
        requests,
        notifier,
        quit,
        settings,
        clock,
    );
    if !matches!(end, LoopEnd::Unproven { .. }) {
        // Teardown completed (or never had anything to do): the objects may be released now.
        drop(ManuallyDrop::into_inner(backend));
        drop(ManuallyDrop::into_inner(presenter));
    }
    end
}

#[expect(
    clippy::too_many_arguments,
    reason = "keeps loop dependencies explicit at setup"
)]
fn drive<B, P, U>(
    backend: &mut B,
    presenter: &mut P,
    ui: &mut U,
    requests: &RequestReader,
    notifier: &Arc<Notifier>,
    quit: &AtomicBool,
    settings: &LoopSettings,
    clock: &dyn Clock,
) -> LoopEnd
where
    B: Backend,
    P: Presenter<Handles = B::Handles>,
    U: UiLink,
{
    if settings.updates().is_some() && !backend.supports_deadline() {
        requests.end();
        return LoopEnd::Failed {
            message: "the update scheduler needs timed waits, which this backend does not provide"
                .to_owned(),
        };
    }
    if let Some(updates) = settings.updates() {
        updates.control().bind(notifier);
        if let Some(metrics) = updates.metrics() {
            metrics.bind(notifier);
        }
    }
    // Setup takes the first batch as a whole.
    let first = requests.take();
    let Some(mut desc) = first.open else {
        requests.end();
        return LoopEnd::NoWindow;
    };
    if first.close {
        requests.end();
        return LoopEnd::Closed;
    }
    if quit.load(Ordering::SeqCst) {
        requests.end();
        return LoopEnd::Quit;
    }
    if let Some(clear) = first.clear {
        desc.clear = clear;
    }
    let mut state = Loop {
        input: InputState {
            mapper: Mapper::new(settings.bindings().clone()),
            // A window is created active: the native layer reports a change only when there is one.
            focused: true,
            minimized: false,
            pixel_size: PixelSize {
                width: 0,
                height: 0,
            },
        },
        backend,
        presenter,
        ui,
        requests,
        notifier,
        quit,
        settings,
        clock,
        points: (desc.width, desc.height),
        updates: settings.updates().cloned().map(UpdateScheduler::new),
        parts: Parts::default(),
    };
    let end = state.setup_and_run(&desc);
    state.teardown(end)
}

impl<B: Backend, P: Presenter<Handles = B::Handles>, U: UiLink> Loop<'_, B, P, U> {
    /// Creates the window, arms the notifier, starts the presenter and runs the passes. Whatever the end
    /// is, `self.parts` says what exists.
    fn setup_and_run(&mut self, desc: &crate::desc::WindowDesc) -> LoopEnd {
        let created = match self.backend.create_window(desc) {
            Ok(created) => created,
            Err(message) => {
                return LoopEnd::Failed {
                    message: format!("cannot create the window: {message}"),
                };
            }
        };
        self.parts.window = true;
        self.input.pixel_size = created.pixel_size;
        if let Err(refused) = self.notifier.arm(self.backend.wake_target()) {
            return LoopEnd::Failed {
                message: format!("cannot arm the notifier: {refused}"),
            };
        }
        self.parts.armed = true;
        if let Err(message) = self
            .presenter
            .start(created.handles, desc, created.pixel_size)
        {
            return LoopEnd::Failed {
                message: format!("cannot start the presenter: {message}"),
            };
        }
        self.parts.presenter_started = true;
        let mut pass = Pass {
            exhausted: false,
            opened: OpenedEvent::Waiting,
            close: CloseEvent::Idle,
            new_size: None,
            redraw: false,
        };
        loop {
            if let Some(end) = self.pass(&mut pass) {
                return end;
            }
        }
    }

    /// A coherent snapshot of the input state, for the UI VM's input delivery (milestone 5-7); it consumes nothing.
    #[expect(
        dead_code,
        reason = "milestone 5-7 reads the snapshot; this issue delivers no input to the UI VM"
    )]
    fn input_snapshot(&mut self) -> ck_input::InputSnapshot {
        self.input.mapper.snapshot()
    }

    /// Acknowledges the edges up to a snapshot (milestone 5-7).
    #[expect(dead_code, reason = "milestone 5-7 acknowledges the snapshot it took")]
    fn acknowledge_input(&mut self, sequence: u128) {
        self.input.mapper.acknowledge(sequence);
    }

    fn quit_requested(&self) -> bool {
        self.quit.load(Ordering::SeqCst)
    }

    /// One pass (design §4.2). `Some` is the end of the loop.
    #[expect(
        clippy::too_many_lines,
        reason = "one bounded window pass keeps phase order visible"
    )]
    fn pass(&mut self, pass: &mut Pass) -> Option<LoopEnd> {
        // 1. Pump once. Sleep only when nothing is waiting anywhere, and the previous pass saw every
        //    queue exhausted rather than capped.
        let waiting =
            pass.opened == OpenedEvent::ToPost || matches!(pass.close, CloseEvent::ToPost(_));
        self.refresh_updates(pass);
        let wait = if pass.exhausted && !waiting && !self.notifier.take_pending() {
            Wait::UntilEvent
        } else {
            Wait::Poll
        };
        let mut absorbed = 0_usize;
        {
            let close = &mut pass.close;
            let size = &mut pass.new_size;
            let redraw = &mut pass.redraw;
            let input = &mut self.input;
            // The callback only records, in constant work (a mapper call is bounded by the bindings that name the
            // key, at most 64 × 8): it never calls back into the backend.
            let mut record = |event: NativeEvent| match event {
                NativeEvent::Key { key, down, repeat } => input.mapper.key(key, down, repeat),
                NativeEvent::KeyResync(states) => input.mapper.resync(&states),
                NativeEvent::FocusLost => {
                    input.mapper.focus_lost();
                    input.focused = false;
                }
                NativeEvent::FocusGained => input.focused = true,
                NativeEvent::Minimized => {
                    input.mapper.focus_lost();
                    input.minimized = true;
                }
                NativeEvent::Restored => input.minimized = false,
                NativeEvent::CloseButton | NativeEvent::EscapePressed => {
                    if *close == CloseEvent::Idle {
                        *close = CloseEvent::ToPost(if event == NativeEvent::CloseButton {
                            CloseSource::Button
                        } else {
                            CloseSource::Key
                        });
                    } else {
                        absorbed += 1;
                    }
                }
                NativeEvent::PixelSizeChanged { width, height } => {
                    let pixel_size = PixelSize { width, height };
                    input.pixel_size = pixel_size;
                    if width == 0 || height == 0 {
                        input.mapper.focus_lost();
                    }
                    *size = Some(pixel_size);
                }
                NativeEvent::NeedsDisplay => *redraw = true,
            };
            if let (Some(scheduler), Wait::UntilEvent) = (&self.updates, wait) {
                if scheduler.active && scheduler.outstanding.is_none() {
                    if let Some(deadline) = scheduler.deadline() {
                        self.backend.pump_until(
                            &mut record,
                            deadline,
                            self.settings.native_events(),
                        );
                    } else {
                        self.backend.pump(
                            &mut record,
                            Wait::UntilEvent,
                            self.settings.native_events(),
                        );
                    }
                } else {
                    self.backend
                        .pump(&mut record, wait, self.settings.native_events());
                }
            } else {
                self.backend
                    .pump(&mut record, wait, self.settings.native_events());
            }
        }
        self.refresh_updates(pass);
        // The close action (design §10.1): a rising edge requests the close with source `key`, exactly as Escape did
        // - one outstanding at a time, later presses absorbed and counted below. Escape from the GLFW backend
        // (`EscapePressed`) took its own path above.
        let presses = usize::try_from(self.input.mapper.take_close_presses()).unwrap_or(usize::MAX);
        if presses > 0 {
            if pass.close == CloseEvent::Idle {
                pass.close = CloseEvent::ToPost(CloseSource::Key);
                absorbed = absorbed.saturating_add(presses - 1);
            } else {
                absorbed = absorbed.saturating_add(presses);
            }
        }
        if absorbed > 0 {
            log(
                Level::Debug,
                format_args!("{absorbed} close request(s) absorbed while one was outstanding"),
            );
        }
        // 2. The quit flag, now and between the following steps.
        if self.quit_requested() {
            return Some(LoopEnd::Quit);
        }
        // 3. The request slot, once.
        let changes = self.requests.take();
        if let Some(clear) = changes.clear {
            self.presenter.set_clear(clear);
            self.presenter.request_redraw();
        }
        if changes.close {
            return Some(LoopEnd::Closed);
        }
        if self.quit_requested() {
            return Some(LoopEnd::Quit);
        }
        // 4. Presenter reports, at most the cap.
        let reports_exhausted = match self.take_reports(pass) {
            Ok(exhausted) => exhausted,
            Err(end) => return Some(end),
        };
        if self.quit_requested() {
            return Some(LoopEnd::Quit);
        }
        // 5. UI answers, at most the cap.
        let answers_exhausted = match self.take_answers(pass) {
            Ok(exhausted) => exhausted,
            Err(end) => return Some(end),
        };
        if self.ui.is_disconnected() {
            return Some(ui_ended());
        }
        if self.quit_requested() {
            return Some(LoopEnd::Quit);
        }
        // 6. Post the events that are waiting.
        if let Some(end) = self.post_waiting(pass) {
            return Some(end);
        }
        self.refresh_updates(pass);
        let close_blocked = matches!(pass.close, CloseEvent::Blocked(_));
        if !close_blocked && let Some(end) = self.post_update(pass) {
            return Some(end);
        }
        // 7. A changed pixel size and a redraw request, to the presenter.
        if let Some(size) = pass.new_size.take() {
            self.presenter.set_pixel_size(size.width, size.height);
        }
        if std::mem::take(&mut pass.redraw) {
            self.presenter.request_redraw();
        }
        pass.exhausted = reports_exhausted && answers_exhausted;
        None
    }

    fn refresh_updates(&mut self, pass: &Pass) {
        let Some(scheduler) = &mut self.updates else {
            return;
        };
        if let Some(metrics) = &scheduler.metrics {
            // The loop's boundary for the measurement windows: a requested window is adopted at the start of a pass.
            metrics.boundary(self.clock.now());
        }
        let (enabled, epoch) = scheduler.control.state();
        let eligible = enabled
            && pass.opened == OpenedEvent::Posted
            && self.input.focused
            && !self.input.minimized
            && self.input.pixel_size.width != 0
            && self.input.pixel_size.height != 0;
        let now = self.clock.now();
        scheduler.refresh(now, eligible, epoch);
        if let Some(metrics) = &scheduler.metrics {
            // The loop has examined its schedule through `now`: the measurement windows' progress fence.
            metrics.accounted(now);
        }
    }

    /// The teardown has begun: the schedule is examined through now, once more, so a measured window that ended after the last pass
    /// still counts the opportunities that fell due before its end.
    fn close_update_accounts(&mut self) {
        let now = self.clock.now();
        if let Some(scheduler) = &mut self.updates {
            scheduler.finish(now);
        }
    }

    fn post_update(&mut self, _pass: &mut Pass) -> Option<LoopEnd> {
        let Some(scheduler) = &mut self.updates else {
            return None;
        };
        if !scheduler.active || scheduler.outstanding.is_some() || scheduler.pending.is_none() {
            return None;
        }
        let now = self.clock.now();
        let elapsed = scheduler
            .last_post
            .map_or(Duration::ZERO, |last| now.saturating_duration_since(last));
        let dt = elapsed.min(scheduler.settings.max_delta());
        let sequence = scheduler.sequence.saturating_add(1);
        let snapshot = self.input.mapper.snapshot();
        let input_sequence = snapshot.sequence;
        let event = UiEvent::Update(UpdateEvent {
            sequence,
            elapsed,
            dt,
            metrics: WindowMetrics {
                points: self.points,
                pixels: self.input.pixel_size,
            },
            input: snapshot,
        });
        match self.ui.post(event) {
            Ok(()) => {
                if let Some(metrics) = &scheduler.metrics {
                    metrics.delivered(now);
                }
                self.input.mapper.acknowledge(input_sequence);
                scheduler.sequence = sequence;
                scheduler.last_post = Some(now);
                scheduler.pending = None;
                scheduler.outstanding = Some(OutstandingUpdate {
                    sequence,
                    epoch: scheduler.epoch,
                });
                None
            }
            Err(PostError::Full) => None,
            Err(PostError::Disconnected) => Some(ui_ended()),
        }
    }

    /// Takes at most the cap of presenter reports. `Ok(true)` when the presenter had no more.
    fn take_reports(&mut self, pass: &mut Pass) -> Result<bool, LoopEnd> {
        for _ in 0..self.settings.items() {
            match self.presenter.take_report() {
                None => return Ok(true),
                Some(PresenterReport::FirstFrameQueued) => {
                    if pass.opened == OpenedEvent::Waiting {
                        pass.opened = OpenedEvent::ToPost;
                        self.parts.opened = Some(());
                        log(Level::Info, format_args!("window opened"));
                    }
                }
                Some(PresenterReport::Failed { message }) => {
                    return Err(LoopEnd::PresenterFailed {
                        message: presenter_failure(&message),
                    });
                }
            }
        }
        Ok(false)
    }

    /// Takes at most the cap of UI answers and applies the close protocol. `Ok(true)` when the UI link
    /// had no more.
    fn take_answers(&mut self, pass: &mut Pass) -> Result<bool, LoopEnd> {
        for _ in 0..self.settings.items() {
            let Some(UiAnswer { event, answer }) = self.ui.take_answer() else {
                return Ok(true);
            };
            if let Some(scheduler) = &mut self.updates {
                scheduler.answer(&event, &answer)?;
            }
            match (event, answer) {
                (_, Answer::Failed { message }) => {
                    return Err(LoopEnd::CallbackFailed { message });
                }
                (UiEvent::CloseRequested { .. }, Answer::Accept | Answer::NotRegistered) => {
                    return Err(LoopEnd::Closed);
                }
                (UiEvent::CloseRequested { .. }, Answer::Decline) => {
                    pass.close = CloseEvent::Idle;
                }
                (_, Answer::Returned) | (UiEvent::Opened | UiEvent::Update(_), _) => {}
            }
        }
        Ok(false)
    }

    /// Offers the events that are waiting (not yet offered, or refused earlier with `Full`) to the UI link.
    fn post_waiting(&mut self, pass: &mut Pass) -> Option<LoopEnd> {
        if matches!(pass.opened, OpenedEvent::ToPost | OpenedEvent::Blocked) {
            match self.ui.post(UiEvent::Opened) {
                Ok(()) => pass.opened = OpenedEvent::Posted,
                Err(PostError::Full) => pass.opened = OpenedEvent::Blocked,
                Err(PostError::Disconnected) => return Some(ui_ended()),
            }
        }
        if let CloseEvent::ToPost(source) | CloseEvent::Blocked(source) = pass.close {
            match self.ui.post(UiEvent::CloseRequested { source }) {
                Ok(()) => pass.close = CloseEvent::Outstanding,
                Err(PostError::Full) => pass.close = CloseEvent::Blocked(source),
                Err(PostError::Disconnected) => return Some(ui_ended()),
            }
        }
        None
    }

    /// Waits for the presenter to be observed finished, in slices, until the teardown deadline.
    fn await_presenter(&mut self) -> Option<CleanupResult> {
        let until = Instant::now()
            .checked_add(self.settings.presenter_teardown())
            .unwrap_or_else(Instant::now);
        loop {
            let left = until.saturating_duration_since(Instant::now());
            if left.is_zero() {
                return self.presenter.poll_end(Duration::ZERO);
            }
            if let Some(result) = self.presenter.poll_end(left.min(POLL_SLICE)) {
                return Some(result);
            }
        }
    }

    /// Takes the presenter's reports once more, after the teardown wait, and returns the failures among
    /// them in order. Nothing waits: `take_report` never does. Once the presenter was observed finished its
    /// queue is finite, so **every** report is taken, whatever the per-pass caps: a failure behind other
    /// reports is not hidden. The only bound is [`TERMINAL_REPORTS`], against a presenter that never stops
    /// reporting (a malformed one): reaching it is itself a reported failure, never a silent discard. A
    /// first-frame report this late opens nothing and is dropped.
    fn take_late_failures(&mut self) -> Vec<String> {
        let mut failures = Vec::new();
        for _ in 0..TERMINAL_REPORTS {
            match self.presenter.take_report() {
                None => return failures,
                Some(PresenterReport::FirstFrameQueued) => {}
                Some(PresenterReport::Failed { message }) => {
                    failures.push(presenter_failure(&message));
                }
            }
        }
        failures.push(presenter_failure(&format!(
            "its report queue did not end within {TERMINAL_REPORTS} reports at teardown; the rest were left unread"
        )));
        failures
    }

    /// The end after teardown completed: a clean end takes the first late presenter failure as its own
    /// failure, and every other late failure (or all of them next to an end that is already a failure) gets
    /// one `error` record.
    fn settle(end: LoopEnd, late: Vec<String>) -> LoopEnd {
        let mut late = late.into_iter();
        let end = match (end, late.next()) {
            (LoopEnd::NoWindow | LoopEnd::Closed | LoopEnd::Quit, Some(first)) => {
                LoopEnd::PresenterFailed { message: first }
            }
            (end, Some(first)) => {
                log(Level::Error, format_args!("{first}"));
                end
            }
            (end, None) => end,
        };
        for message in late {
            log(Level::Error, format_args!("{message}"));
        }
        end
    }

    /// The teardown, in order, never from inside `pump`. `end` is how the loop ended; the result is `end`
    /// unless the resources could not be proven released, or the presenter, observed finished, had
    /// reported a failure the loop had not yet taken (see the crate documentation).
    fn teardown(&mut self, end: LoopEnd) -> LoopEnd {
        self.requests.end();
        let mut unproven = None;
        let mut late = Vec::new();
        if self.parts.presenter_started {
            self.presenter.request_stop();
            // The presenter's stop is where the measured window's end is taken (the application's presenter does it): the schedule
            // is examined through now, which is at or after that end.
            self.close_update_accounts();
            match self.await_presenter() {
                Some(CleanupResult::Proven) => {}
                Some(CleanupResult::Unproven { reason }) => {
                    unproven = Some(format!("the presenter's cleanup is unproven: {reason}"));
                }
                None => {
                    unproven = Some(
                        "the presenter was not observed finished before the teardown deadline"
                            .to_owned(),
                    );
                }
            }
            // After the wait and before anything is disarmed or destroyed: a finished presenter's queue is
            // complete; one that missed the deadline gives what is there.
            late = self.take_late_failures();
        }
        if unproven.is_none()
            && self.parts.armed
            && self.notifier.disarm(self.settings.disarm()).is_err()
        {
            unproven = Some("a native wake was still in flight at the disarm deadline".to_owned());
        }
        if let Some(reason) = unproven {
            // Nothing is destroyed: the presenter's or a native wake's objects may still be in use.
            let reason = match &end {
                LoopEnd::CallbackFailed { message }
                | LoopEnd::Failed { message }
                | LoopEnd::PresenterFailed { message } => {
                    format!("{reason} (the loop had ended with: {message})")
                }
                _ => reason,
            };
            for message in &late {
                log(Level::Error, format_args!("{message}"));
            }
            return LoopEnd::Unproven { reason };
        }
        if self.parts.window {
            self.backend.destroy_window();
            self.parts.window = false;
        }
        self.backend.terminate();
        if self.parts.opened.is_some() {
            log(Level::Info, format_args!("window closed"));
        }
        Self::settle(end, late)
    }
}

fn ui_ended() -> LoopEnd {
    LoopEnd::Failed {
        message: "the ui VM ended".to_owned(),
    }
}

