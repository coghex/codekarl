#!/usr/bin/env python3
"""Write the deterministic lookup tables used by the weather rules."""

import math
from pathlib import Path


def rounded(value: float) -> int:
    """Round once, with halves away from zero."""
    return math.floor(value + 0.5) if value >= 0 else -math.floor(-value + 0.5)


def tilt(day: int) -> float:
    return math.tan(math.radians(-23.44 * math.cos(math.radians(360 * (day + 10) / 365))))


def generate() -> str:
    cosine = [rounded(math.cos(math.radians(i / 10)) * 1_000_000) for i in range(3600)]
    tangent = [rounded(math.tan(math.radians(i / 10)) * 1_000_000) for i in range(851)]
    half_day = [rounded(math.degrees(math.acos(i / 1000)) * 4) for i in range(-1000, 1001)]
    declination = [rounded(tilt(day) * 1_000_000) for day in range(1, 366)]
    declination.insert(59, rounded((tilt(59) + tilt(60)) * 500_000))
    lines = [
        "# Generated by tools/generate_weather.py; values are rounded once.",
        "swing_coast = 48",
        "swing_inland = 75",
        "lag_minutes = 150",
        "fade_minutes = 120",
        "wind_sea_friction = 15000",
        "wind_sea_factor = 690",
        "wind_land_friction = 70000",
        "wind_land_factor = 330",
        "wind_slope_blocks = 2",
        "wind_belt_latitude = 60000",
        "steer_friction = 1000",
        "steer_factor = 1000",
        "steer_contrast = 1225",
        "steer_smooth_blocks = 5",
        "steer_smooth_passes = 3",
        "steer_drift_west = 100",
        "steer_drift_pole = 200",
        "meet_share = 500",
        "",
    ]
    for name, values in (
        ("cosine", cosine),
        ("tangent", tangent),
        ("declination", declination),
        ("half_day", half_day),
    ):
        lines.append(f"{name} = [")
        for start in range(0, len(values), 12):
            lines.append("    " + ", ".join(map(str, values[start : start + 12])) + ",")
        lines.extend(["]", ""])
    return "\n".join(lines)


if __name__ == "__main__":
    (Path(__file__).resolve().parent.parent / "assets/game/weather.toml").write_text(
        generate(), encoding="utf-8"
    )
